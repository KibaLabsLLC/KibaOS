#!/usr/bin/env bash
# Check that ci/system-tools.sh takes a tool from pacman only when the package
# and its binaries are really there, that a GN too old for the tree's .gn is
# left out, that Chromium's prebuilt clang is kept and what an earlier
# bootstrap put in its path is cleared, and that the DEPS-side, GN-side and
# package-build answers match what it substituted.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TOOLS="${SCRIPT_DIR}/system-tools.sh"

fail() {
  echo "system-tools test: $1" >&2
  exit 1
}

tmp="$(mktemp -d "${TMPDIR:-/tmp}/kibaos-system-tools-test.XXXXXX")"
trap 'rm -rf "${tmp}"' EXIT

# A pacman that reports the packages listed in FAKE_PACMAN_INSTALLED as
# installed, and whose installs are never reached in these cases.
mkdir -p "${tmp}/bin"
cat >"${tmp}/pacman" <<'EOF'
#!/bin/sh
case "$1" in
  -Qq) grep -Fxq "$2" "${FAKE_PACMAN_INSTALLED}" ;;
  -S) exit 0 ;;
  *) exit 2 ;;
esac
EOF
chmod +x "${tmp}/pacman"

fake_bin() {
  printf '#!/bin/sh\nexit 0\n' >"${tmp}/bin/$1"
  chmod +x "${tmp}/bin/$1"
}

src="${tmp}/src"
mkdir -p "${src}"
: >"${src}/DEPS"
# The tree's .gn names its interpreter and its flags, which recent GN writes as
# a list; the packaged GN has to be new enough to read that.
cat >"${src}/.gn" <<'EOF'
buildconfig = "//build/config/BUILDCONFIG.gn"
script_executable = [
  "//third_party/cpython3/host/bin/python3",
  "-ES",
]
EOF

state="${src}/out/.kibaos"
clang_base="${src}/third_party/llvm-build/Release+Asserts"

# run_link [NAME=VALUE ...] -- runs the helper with the fake pacman and bin dir;
# extra assignments are handed to env and reach the script as its environment.
run_link() {
  env FAKE_PACMAN_INSTALLED="${tmp}/installed" \
    KIBAOS_SYSTEM_BIN_DIR="${tmp}/bin" \
    KIBAOS_PACMAN_BIN="${tmp}/pacman" \
    "$@" "${TOOLS}" --link "${src}"
}

resolver() {
  env FAKE_PACMAN_INSTALLED="${tmp}/installed" \
    KIBAOS_SYSTEM_BIN_DIR="${tmp}/bin" \
    KIBAOS_PACMAN_BIN="${tmp}/pacman" \
    "$@" "${TOOLS}" --resolver-args "${src}"
}

# A: gn and ninja are packaged and present; the clang packages are irrelevant,
# and Chromium's prebuilt toolchain is left for the resolver to download.
printf 'gn\nninja\n' >"${tmp}/installed"
for bin in gn ninja clang clang++ ld.lld llvm-ar llvm-nm llvm-strip; do
  fake_bin "${bin}"
done

run_link >"${tmp}/link-a.log" 2>&1 || {
  cat "${tmp}/link-a.log" >&2
  fail "link failed with every package installed"
}

[[ -L "${src}/buildtools/linux64/gn" ]] || fail "gn was not linked"
[[ -L "${src}/third_party/ninja/ninja" ]] || fail "ninja was not linked"
[[ ! -e "${clang_base}" ]] ||
  fail "a clang toolchain was put where the prebuilt one is downloaded"
grep -Fxq 'gn=gn' "${state}/system-tools.conf" || fail "gn was not recorded"
grep -Fxq 'ninja=ninja' "${state}/system-tools.conf" ||
  fail "ninja was not recorded"
if grep -q 'clang' "${state}/system-tools.conf"; then
  fail "a clang was recorded as substituted"
fi
[[ -f "${state}/system-tools.gn" && ! -s "${state}/system-tools.gn" ]] ||
  fail "the gn-argument file is not the empty one the builds cat"
grep -q "clang: keeping Chromium's prebuilt toolchain" "${tmp}/link-a.log" ||
  fail "the run did not say it keeps Chromium's clang"

resolver >"${tmp}/resolver-a"
grep -Fxq 'src/buildtools/linux64' "${tmp}/resolver-a" ||
  fail "the resolver is not told to skip GN"
grep -Fxq 'src/third_party/ninja' "${tmp}/resolver-a" ||
  fail "the resolver is not told to skip Ninja"
if grep -Fxq 'src/third_party/llvm-build/Release+Asserts' "${tmp}/resolver-a"; then
  fail "the resolver skips the clang toolchain this build keeps"
fi

# B: an earlier bootstrap had taken the packaged clang. Its links, its wrapper
# and the wrapper's cache go so the download lands in their place, while a
# binary at that path that this script did not write stays.
mkdir -p "${clang_base}/bin" "${clang_base}/lib"
ln -sfn "${tmp}/bin/clang" "${clang_base}/bin/clang"
cat >"${clang_base}/bin/clang++" <<'EOF'
#!/bin/bash
# Generated by ci/system-tools.sh.
exit 0
EOF
chmod +x "${clang_base}/bin/clang++"
printf -- '-fno-module-local-hints\n' >"${clang_base}/lib/kibaos-clang-rejected-args"
printf '#!/bin/sh\nexit 0\n' >"${clang_base}/bin/llvm-ar"
chmod +x "${clang_base}/bin/llvm-ar"

run_link >"${tmp}/link-b.log" 2>&1 || {
  cat "${tmp}/link-b.log" >&2
  fail "link failed with an earlier clang in the toolchain path"
}

[[ ! -e "${clang_base}/bin/clang" ]] ||
  fail "an earlier clang link was left in the prebuilt toolchain's path"
[[ ! -e "${clang_base}/bin/clang++" ]] ||
  fail "the old clang wrapper was left in place"
[[ ! -e "${clang_base}/lib/kibaos-clang-rejected-args" ]] ||
  fail "the old wrapper cache was left in place"
[[ -f "${clang_base}/bin/llvm-ar" ]] ||
  fail "a toolchain binary that was not ours was removed"

# C: ninja is not packaged and installing is not allowed; gn still is, and each
# tool is answered on its own.
rm -rf "${src}/buildtools" "${src}/third_party/ninja" "${clang_base}" \
  "${src}/out"
printf 'gn\n' >"${tmp}/installed"

run_link KIBAOS_PACMAN=0 >"${tmp}/link-c.log" 2>&1 || {
  cat "${tmp}/link-c.log" >&2
  fail "link failed when only some tools are available"
}

[[ -L "${src}/buildtools/linux64/gn" ]] ||
  fail "gn was not linked in the partial case"
[[ ! -e "${src}/third_party/ninja/ninja" ]] ||
  fail "ninja was linked without its package"
grep -Fxq 'gn=gn' "${state}/system-tools.conf" || fail "gn was not recorded"
if grep -Fxq 'ninja=ninja' "${state}/system-tools.conf"; then
  fail "ninja was recorded without its package"
fi

resolver KIBAOS_PACMAN=0 >"${tmp}/resolver-c"
grep -Fxq 'src/buildtools/linux64' "${tmp}/resolver-c" ||
  fail "the partial case does not skip GN"
if grep -Fxq 'src/third_party/ninja' "${tmp}/resolver-c"; then
  fail "the partial case skips a Ninja it did not substitute"
fi

# D: switched off, nothing is substituted or skipped.
rm -rf "${src}/buildtools" "${src}/third_party/ninja" "${src}/out"
run_link KIBAOS_SYSTEM_TOOLS=0 >"${tmp}/link-d.log" 2>&1 ||
  fail "link failed when system tools are disabled"

[[ ! -e "${src}/buildtools" ]] || fail "gn was linked while switched off"
[[ ! -s "${state}/system-tools.conf" ]] ||
  fail "state was recorded while switched off"
[[ ! -s "${state}/system-tools.gn" ]] ||
  fail "GN arguments were written while switched off"

resolver KIBAOS_SYSTEM_TOOLS=0 >"${tmp}/resolver-d"
[[ ! -s "${tmp}/resolver-d" ]] ||
  fail "the resolver arguments are not empty while switched off"

# E: a gn that fails for an unrelated reason is still usable; only the list
# form it cannot parse makes the package too old.
rm -rf "${src}/buildtools" "${src}/out"
printf 'gn\n' >"${tmp}/installed"
cat >"${tmp}/bin/gn" <<'EOF'
#!/bin/sh
echo 'ERROR: No buildconfig file.' >&2
exit 1
EOF
chmod +x "${tmp}/bin/gn"

run_link KIBAOS_PACMAN=0 >"${tmp}/link-e0.log" 2>&1 || {
  cat "${tmp}/link-e0.log" >&2
  fail "link failed when the packaged gn fails for its own reasons"
}
[[ -L "${src}/buildtools/linux64/gn" ]] ||
  fail "a gn that fails for an unrelated reason was dropped"

# F: the packaged GN is older than the tree's list-form .gn, so GN keeps
# Chromium's copy and the resolver still fetches it.
rm -rf "${src}/buildtools" "${src}/third_party/ninja" "${src}/out"
printf 'gn\nninja\n' >"${tmp}/installed"
cat >"${tmp}/bin/gn" <<'EOF'
#!/bin/sh
root=
for arg in "$@"; do
  case "${arg}" in
    --root=*) root="${arg#--root=}" ;;
  esac
done
if [ -n "${root}" ] && grep -q 'script_executable = \[' "${root}/.gn"; then
  echo 'ERROR at //.gn:18:21: This is not a string.' >&2
  exit 1
fi
exit 0
EOF
chmod +x "${tmp}/bin/gn"

# A link left by an earlier run must not survive the fallback, or the
# resolver's download would find the old gn in its place.
mkdir -p "${src}/buildtools/linux64"
ln -sfn "${tmp}/bin/gn" "${src}/buildtools/linux64/gn"

run_link KIBAOS_PACMAN=0 >"${tmp}/link-f.log" 2>&1 || {
  cat "${tmp}/link-f.log" >&2
  fail "link failed when the packaged gn cannot read the tree's .gn"
}

if [[ -L "${src}/buildtools/linux64/gn" ]]; then
  fail "a gn that cannot read the tree's .gn was linked anyway"
fi
grep -q 'cannot read the list-form script_executable' "${tmp}/link-f.log" ||
  fail "the old gn was left out without saying why"
[[ -L "${src}/third_party/ninja/ninja" ]] ||
  fail "ninja was dropped along with gn"
if grep -Fxq 'gn=gn' "${state}/system-tools.conf"; then
  fail "an unusable gn was recorded as substituted"
fi

resolver KIBAOS_PACMAN=0 >"${tmp}/resolver-f"
if grep -Fxq 'src/buildtools/linux64' "${tmp}/resolver-f"; then
  fail "the resolver skips a GN that was not substituted"
fi
grep -Fxq 'src/third_party/ninja' "${tmp}/resolver-f" ||
  fail "the resolver stopped skipping Ninja"

# G: the package build fails fast on a GN link that cannot read the tree's
# .gn, and accepts one that can.
mkdir -p "${src}/buildtools/linux64"
ln -sfn "${tmp}/bin/gn" "${src}/buildtools/linux64/gn"

status=0
"${TOOLS}" --check-gn "${src}" >"${tmp}/check-gn-bad.log" 2>&1 || status=$?
[[ ${status} -ne 0 ]] ||
  fail "--check-gn accepted a GN that cannot read the tree's .gn"
grep -q 'cannot read this tree' "${tmp}/check-gn-bad.log" ||
  fail "--check-gn did not say what is wrong"
grep -q 'bootstrap-chromium-src.sh' "${tmp}/check-gn-bad.log" ||
  fail "--check-gn did not say how to fix it"

printf '#!/bin/sh\nexit 0\n' >"${tmp}/bin/gn"
chmod +x "${tmp}/bin/gn"
"${TOOLS}" --check-gn "${src}" >"${tmp}/check-gn-ok.log" 2>&1 || {
  cat "${tmp}/check-gn-ok.log" >&2
  fail "--check-gn rejected a GN that can read the tree's .gn"
}

rm -f "${src}/buildtools/linux64/gn"
"${TOOLS}" --check-gn "${src}" >/dev/null 2>&1 ||
  fail "--check-gn failed without a GN link"

echo "system-tools test passed"
