#!/usr/bin/env bash
# ci/repair-pruned-gn.py: a gnrt rust crate BUILD.gn whose `sources`/`inputs`
# lists the Lumen import emptied to `[]` still parses, so it never shows up as
# a broken GN file -- it fails much later, when rustc_wrapper.py rejects the
# files rustc discovered and GN never declared. The repair refills those lists:
# sources from the vendored crate's own src/ tree, inputs from the upstream
# mirror's list at the pinned sha, keeping only the entries whose path exists
# in the checkout; a list collapsed to one `inputs = []` line is expanded; a
# crate with nothing derivable is left alone; and the same tree always yields
# the same repair.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
tool="${repo_root}/ci/repair-pruned-gn.py"

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

lumen="${work}/lumen"
mirror="${work}/chromium-mirror"
out="${work}/out"
log="${work}/log"

fail() {
    echo "FAIL: $*" >&2
    if [[ -s ${log} ]]; then
        sed 's/^/    /' "${log}" >&2
    fi
    exit 1
}

write() {
    local path=$1
    shift
    mkdir -p "$(dirname "${path}")"
    printf '%s\n' "$@" >"${path}"
}

vendor="third_party/rust/chromium_crates_io/vendor"
url="//${vendor}"

# --- Lumen's tree: the lists the import emptied, and their vendored crates ---

# demo: both lists emptied, the shape the pruner leaves when it deletes every
# value line between the brackets.
write "${lumen}/third_party/rust/demo/v1/BUILD.gn" \
    '# @generated by gnrt' \
    '' \
    'import("//build/rust/cargo_crate.gni")' \
    '' \
    'cargo_crate("lib") {' \
    '  crate_name = "demo"' \
    '  epoch = "1"' \
    '  crate_type = "rlib"' \
    "  crate_root = \"${url}/demo-v1/src/lib.rs\"" \
    '  sources = [' \
    '  ]' \
    '  inputs = [' \
    '  ]' \
    '' \
    '  cargo_pkg_name = "demo"' \
    '  allow_unsafe = false' \
    '  deps = []' \
    '  features = []' \
    '  visibility = [ "//third_party/rust/*" ]' \
    '}'

# terse: inputs collapsed to a single line by the pruner.
write "${lumen}/third_party/rust/terse/v1/BUILD.gn" \
    '# @generated by gnrt' \
    '' \
    'import("//build/rust/cargo_crate.gni")' \
    '' \
    'cargo_crate("lib") {' \
    '  crate_name = "terse"' \
    '  epoch = "1"' \
    '  crate_type = "rlib"' \
    "  crate_root = \"${url}/terse-v1/src/lib.rs\"" \
    '  sources = [' \
    '  ]' \
    '  inputs = []' \
    '' \
    '  cargo_pkg_name = "terse"' \
    '  allow_unsafe = false' \
    '  deps = []' \
    '  visibility = [ "//third_party/rust/*" ]' \
    '}'

# plain: emptied sources, but upstream declares no extra inputs either, so the
# empty `inputs = []` is the crate's real state and must stay that way.
write "${lumen}/third_party/rust/plain/v1/BUILD.gn" \
    '# @generated by gnrt' \
    '' \
    'import("//build/rust/cargo_crate.gni")' \
    '' \
    'cargo_crate("lib") {' \
    '  crate_name = "plain"' \
    '  epoch = "1"' \
    '  crate_type = "rlib"' \
    "  crate_root = \"${url}/plain-v1/src/lib.rs\"" \
    '  sources = [' \
    '  ]' \
    '  inputs = []' \
    '' \
    '  cargo_pkg_name = "plain"' \
    '  allow_unsafe = false' \
    '  deps = []' \
    '  visibility = [ "//third_party/rust/*" ]' \
    '}'

# orphan: nothing to derive from -- no vendored crate and no upstream file.
write "${lumen}/third_party/rust/orphan/v1/BUILD.gn" \
    '# @generated by gnrt' \
    '' \
    'cargo_crate("lib") {' \
    '  crate_name = "orphan"' \
    '  epoch = "1"' \
    '  crate_type = "rlib"' \
    "  crate_root = \"${url}/orphan-v1/src/lib.rs\"" \
    '  sources = [' \
    '  ]' \
    '  inputs = []' \
    '  cargo_pkg_name = "orphan"' \
    '}'

write "${lumen}/${vendor}/demo-v1/src/lib.rs" 'pub mod inner;'
write "${lumen}/${vendor}/demo-v1/src/inner.rs" 'pub fn inner() {}'
write "${lumen}/${vendor}/demo-v1/examples/demo.md" 'example'
write "${lumen}/${vendor}/terse-v1/src/lib.rs" 'pub fn terse() {}'
write "${lumen}/${vendor}/terse-v1/examples/demo.md" 'example'
write "${lumen}/${vendor}/plain-v1/src/lib.rs" 'pub fn plain() {}'

# --- The upstream mirror at the pinned sha: what gnrt generated ---

write "${mirror}/third_party/rust/demo/v1/BUILD.gn" \
    'cargo_crate("lib") {' \
    '  crate_name = "demo"' \
    '  epoch = "1"' \
    '  sources = [' \
    "    \"${url}/demo-v1/src/inner.rs\"," \
    "    \"${url}/demo-v1/src/lib.rs\"," \
    '  ]' \
    '  inputs = [' \
    "    \"${url}/demo-v1/examples/demo.md\"," \
    "    \"${url}/demo-v1/examples/gone.md\"," \
    '  ]' \
    '}'

# gnrt emits a single entry list on one line, which is the shape that used to
# slip past the value-line alignment entirely.
write "${mirror}/third_party/rust/terse/v1/BUILD.gn" \
    'cargo_crate("lib") {' \
    '  crate_name = "terse"' \
    '  epoch = "1"' \
    "  sources = [ \"${url}/terse-v1/src/lib.rs\" ]" \
    "  inputs = [ \"${url}/terse-v1/examples/demo.md\" ]" \
    '}'

write "${mirror}/third_party/rust/plain/v1/BUILD.gn" \
    'cargo_crate("lib") {' \
    '  crate_name = "plain"' \
    '  epoch = "1"' \
    '  sources = [' \
    "    \"${url}/plain-v1/src/lib.rs\"," \
    '  ]' \
    '  inputs = []' \
    '}'

git -C "${mirror}" init -q
git -C "${mirror}" add -A
git -C "${mirror}" -c user.name=t -c user.email=t@example.invalid \
    commit -qm 'upstream'

echo "==> --check names the emptied lists an emptied list alone hides"
status=0
python3 "${tool}" --check --lumen "${lumen}" >"${log}" 2>&1 || status=$?
[[ ${status} -eq 1 ]] || fail "--check exited ${status}, expected 1"
grep -q 'INCOMPLETE third_party/rust/demo/v1/BUILD.gn' "${log}" ||
    fail "--check did not name the crate with both lists emptied"
grep -q 'INCOMPLETE third_party/rust/terse/v1/BUILD.gn' "${log}" ||
    fail "--check did not name the crate whose inputs are one empty line"
if grep -q 'orphan' "${log}"; then
    fail "--check named a crate with nothing to derive from"
fi

echo "==> the mirror supplies the inputs the vendor tree cannot"
python3 "${tool}" --check --lumen "${lumen}" --chromium "${mirror}" \
    --ref HEAD >"${log}" 2>&1 || status=$?
[[ ${status} -eq 1 ]] || fail "--check with a mirror exited ${status}, expected 1"
grep -q 'emptied inputs, sources list(s)' "${log}" ||
    fail "the mirror's inputs were not reported as fillable"

echo "==> sources come from the vendor tree, inputs from upstream"
python3 "${tool}" --lumen "${lumen}" --chromium "${mirror}" --ref HEAD \
    --out "${out}" >"${log}" 2>&1 || fail "the repair failed"
grep -q '3 with emptied rust lists' "${log}" ||
    fail "the repair did not scan the three fillable crates"

demo="${out}/third_party/rust/demo/v1/BUILD.gn"
[[ -f ${demo} ]] || fail "demo was not repaired"
for want in "${url}/demo-v1/src/lib.rs" "${url}/demo-v1/src/inner.rs" \
    "${url}/demo-v1/examples/demo.md"; do
    grep -qF "\"${want}\"" "${demo}" ||
        fail "demo's repair is missing ${want}"
done
if grep -qF 'gone.md' "${demo}"; then
    fail "demo declares an input whose path is not in the checkout"
fi

terse="${out}/third_party/rust/terse/v1/BUILD.gn"
[[ -f ${terse} ]] || fail "terse was not repaired"
grep -qx '  inputs = \[' "${terse}" ||
    fail "terse's one-line inputs were not expanded to a list"
grep -qF "\"${url}/terse-v1/examples/demo.md\"" "${terse}" ||
    fail "terse's input was not restored"
grep -qF "\"${url}/terse-v1/src/lib.rs\"" "${terse}" ||
    fail "terse's sources were not restored"

plain="${out}/third_party/rust/plain/v1/BUILD.gn"
[[ -f ${plain} ]] || fail "plain was not repaired"
grep -qF "\"${url}/plain-v1/src/lib.rs\"" "${plain}" ||
    fail "plain's sources were not restored"
grep -qx '  inputs = \[\]' "${plain}" ||
    fail "plain gained inputs upstream never declared"

if [[ -e "${out}/third_party/rust/orphan/v1/BUILD.gn" ]]; then
    fail "a crate with nothing derivable was written as a repair"
fi

echo "==> the repaired tree passes the check the raw tree failed"
python3 "${tool}" --check --lumen "${lumen}" --chromium "${mirror}" \
    --ref HEAD --overlay "${out}" >"${log}" 2>&1 ||
    fail "--check still fails over the repaired overlay"
grep -q '0 broken, 0 with emptied rust lists' "${log}" ||
    fail "--check does not report the overlay as complete"

echo "==> the same tree produces the same repair"
python3 "${tool}" --lumen "${lumen}" --chromium "${mirror}" --ref HEAD \
    --out "${work}/again" >"${log}" 2>&1 || fail "the second repair failed"
diff -r "${out}" "${work}/again" >"${log}" 2>&1 ||
    fail "the second repair is not byte-identical"

echo "==> all pruned rust list cases passed"
